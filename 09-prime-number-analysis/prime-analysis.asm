.MODEL SMALL
.STACK 100H

.DATA
ARRAY DB 07H,02H,06H,05H,01H,08H,09H,12H,11H
SUM   DB 0H
COUNT DB 0H

.CODE
MAIN PROC

    MOV AX,@DATA
    MOV DS,AX

    XOR AX,AX
    XOR BX,BX
    XOR CX,CX
    XOR DX,DX

    MOV SUM,0H
    MOV COUNT,0H

    LEA SI,ARRAY
    MOV CX,09H

MAIN_LOOP:

    MOV AL,[SI]
    CMP AL,1
    JE NOT_PRIME
    CMP AL,0
    JE NOT_PRIME

    MOV BL,2H

DIV_LOOP:

    CMP AL,BL
    JLE PRIME

    DIV BL
    CMP AH,0H
    JE NOT_PRIME

    XOR AX,AX
    MOV AL,[SI]
    INC BL
    JMP DIV_LOOP

PRIME:
    INC COUNT

NOT_PRIME:
    MOV AL,[SI]
    ADD SUM,AL
    INC SI

    LOOP MAIN_LOOP

    MOV AL,SUM
    MOV BX,0500H
    MOV [BX],AL

    XOR BX,BX
    MOV BL,COUNT

    MOV AX,4C00H
    INT 21H

MAIN ENDP
END MAIN